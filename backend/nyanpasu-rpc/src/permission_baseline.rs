//! The reviewed authorization baseline of every protected resource, and the comparison that
//! reports how a later resource table differs from it.
//!
//! A resource is a command, an event, an HTTP route or a stream. The baseline is a committed
//! text table; [`differences`] aligns two tables by `(kind, name)`, compares every field, and
//! compares admission on every transport for the unresolved caller and every combination of
//! held levels. The permission migration requires an empty difference at every step that is not
//! allowed to change authorization.
//!
//! The baseline holds the permissions the switch put in force. The scope table it replaced is
//! kept, frozen, for [`mapping`], which checks that the switch changed only what the reviewed
//! change list allows.

use std::{
    collections::{BTreeMap, BTreeSet},
    fmt::{self, Debug, Write as _},
    fs,
    path::Path,
};

use nyanpasu_contracts::auth::{Access, Permission, Permissions, Resource};
use nyanpasu_rpc_protocol::{
    CommandEffect, EventName, RpcTarget,
    permission::{RESOURCES, ResourceKind},
};

const BASELINE: &str = "tests/fixtures/permission-baseline.txt";
/// The baseline is exported on Windows. These rows replace the commands whose declarations differ
/// on every other platform, where the `cfg(not(windows))` variant is compiled.
const NOT_WINDOWS: &str = "tests/fixtures/permission-baseline-not-windows.txt";
const HEADER: &str = "# Generated by export_permission_baseline; do not edit.\n# kind | name | permission | sensitive | effect | targets | capabilities | optional_capabilities\n";
const TRANSPORTS: [RpcTarget; 3] = [RpcTarget::Desktop, RpcTarget::Http, RpcTarget::Local];
/// The resources a grant can hold a level on; `meta:read` is held by every resolved caller.
const GRANTABLE: [Resource; 7] = [
    Resource::Proxy,
    Resource::Profile,
    Resource::Settings,
    Resource::System,
    Resource::Logs,
    Resource::Traffic,
    Resource::Remote,
];

#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
enum Kind {
    Command,
    Event,
    Route,
    Stream,
}

/// One protected resource, with every field that takes part in authorization or availability.
#[derive(Debug, Clone, PartialEq, Eq)]
struct Row {
    permission: Permission,
    sensitive: bool,
    /// `query`/`mutation` for commands; events, routes and streams only read.
    effect: String,
    targets: Vec<String>,
    capabilities: Vec<String>,
    optional_capabilities: Vec<String>,
}

type Table = BTreeMap<(Kind, String), Row>;

/// A caller in the comparison: unresolved (no authentication), or resolved with these
/// permissions.
type Caller = Option<Permissions>;

mod mapping;

fn snake(value: impl Debug) -> String {
    let mut name = String::new();
    for (index, character) in format!("{value:?}").chars().enumerate() {
        if character.is_ascii_uppercase() && index > 0 {
            name.push('_');
        }
        name.push(character.to_ascii_lowercase());
    }
    name
}

fn names<T: Debug + Copy>(values: &[T]) -> Vec<String> {
    values.iter().copied().map(snake).collect()
}

fn kind_name(text: &str) -> Kind {
    match text {
        "command" => Kind::Command,
        "event" => Kind::Event,
        "route" => Kind::Route,
        "stream" => Kind::Stream,
        other => panic!("unknown resource kind {other}"),
    }
}

/// A persisted name, `proxy` or `write`, decoded by its serde name.
fn parse_name<T: serde::de::DeserializeOwned>(name: &str) -> T {
    serde_json::from_value(serde_json::Value::from(name))
        .unwrap_or_else(|error| panic!("{name}: {error}"))
}

/// `proxy:write`.
fn parse_permission(text: &str) -> Permission {
    let (resource, access) = text
        .split_once(':')
        .unwrap_or_else(|| panic!("malformed permission {text}"));
    Permission::new(parse_name(resource), parse_name(access))
}

/// The table the current code authorizes against.
fn current() -> Table {
    let mut table = Table::new();
    for resource in RESOURCES {
        let (kind, effect) = match resource.kind {
            ResourceKind::Command(_) => (
                Kind::Command,
                match resource.effect {
                    CommandEffect::Query => "query",
                    CommandEffect::Mutation => "mutation",
                },
            ),
            ResourceKind::Event => (Kind::Event, "read"),
            ResourceKind::Route => (Kind::Route, "read"),
            ResourceKind::Stream => (Kind::Stream, "read"),
        };
        let row = Row {
            permission: resource.permission,
            sensitive: resource.sensitive,
            effect: effect.to_owned(),
            targets: names(resource.targets),
            capabilities: names(resource.capabilities),
            optional_capabilities: names(resource.optional_capabilities),
        };
        let previous = table.insert((kind, resource.name.to_owned()), row);
        assert!(previous.is_none(), "duplicate resource {}", resource.name);
    }
    table
}

fn render(table: &Table) -> String {
    let mut output = String::from(HEADER);
    for ((kind, name), row) in table {
        let line = format!(
            "{} | {name} | {} | {} | {} | {} | {} | {}",
            snake(kind),
            row.permission,
            if row.sensitive { "sensitive" } else { "" },
            row.effect,
            row.targets.join(","),
            row.capabilities.join(","),
            row.optional_capabilities.join(","),
        );
        writeln!(output, "{}", line.trim_end()).unwrap();
    }
    output
}

fn list(field: &str) -> Vec<String> {
    field
        .split(',')
        .filter(|value| !value.is_empty())
        .map(str::to_owned)
        .collect()
}

fn parse(text: &str) -> Table {
    let mut table = Table::new();
    for line in text.lines().filter(|line| !line.starts_with('#')) {
        let columns: Vec<_> = line.split('|').map(str::trim).collect();
        assert_eq!(columns.len(), 8, "malformed row: {line}");
        let row = Row {
            permission: parse_permission(columns[2]),
            sensitive: match columns[3] {
                "sensitive" => true,
                "" => false,
                other => panic!("unknown marking {other}"),
            },
            effect: columns[4].to_owned(),
            targets: list(columns[5]),
            capabilities: list(columns[6]),
            optional_capabilities: list(columns[7]),
        };
        let previous = table.insert((kind_name(columns[0]), columns[1].to_owned()), row);
        assert!(previous.is_none(), "duplicate row: {line}");
    }
    table
}

/// The unresolved caller and every combination of no level, `read` or `write` on each grantable
/// resource.
fn callers() -> Vec<Caller> {
    let mut callers = vec![None];
    let mut combinations = vec![Permissions::NONE];
    for resource in GRANTABLE {
        combinations = combinations
            .into_iter()
            .flat_map(|held| {
                [
                    held,
                    held.with(resource, Access::Read),
                    held.with(resource, Access::Write),
                ]
            })
            .collect();
    }
    callers.extend(combinations.into_iter().map(Some));
    callers
}

/// Whether `caller` is admitted to `row` on `transport`: authentication, exposure, then the
/// requirement. Capabilities depend on the host and are compared as fields instead.
fn admits(row: &Row, transport: RpcTarget, caller: &Caller) -> bool {
    let Some(permissions) = caller else {
        return false;
    };
    row.targets.contains(&snake(transport)) && permissions.permits(row.permission)
}

struct Display<'a>(&'a Caller);

impl fmt::Display for Display<'_> {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self.0 {
            None => f.write_str("unresolved"),
            Some(permissions) => {
                let held: Vec<_> = permissions
                    .iter()
                    .map(|(resource, access)| Permission::new(resource, access).to_string())
                    .collect();
                write!(f, "{{{}}}", held.join(","))
            }
        }
    }
}

/// Every difference between two tables, one line each: added and removed resources, changed
/// fields, and per transport the callers whose admission changed.
fn differences(before: &Table, after: &Table) -> Vec<String> {
    let callers = callers();
    let mut report = Vec::new();
    let keys: BTreeSet<_> = before.keys().chain(after.keys()).collect();
    for key @ (kind, name) in keys {
        let label = format!("{} {name}", snake(kind));
        let (left, right) = match (before.get(key), after.get(key)) {
            (Some(left), Some(right)) => (left, right),
            (Some(_), None) => {
                report.push(format!("{label}: removed"));
                continue;
            }
            (None, Some(_)) => {
                report.push(format!("{label}: added"));
                continue;
            }
            (None, None) => unreachable!(),
        };
        for (field, left, right) in [
            (
                "permission",
                vec![left.permission.to_string()],
                vec![right.permission.to_string()],
            ),
            (
                "sensitive",
                vec![left.sensitive.to_string()],
                vec![right.sensitive.to_string()],
            ),
            (
                "effect",
                vec![left.effect.clone()],
                vec![right.effect.clone()],
            ),
            ("targets", left.targets.clone(), right.targets.clone()),
            (
                "capabilities",
                left.capabilities.clone(),
                right.capabilities.clone(),
            ),
            (
                "optional_capabilities",
                left.optional_capabilities.clone(),
                right.optional_capabilities.clone(),
            ),
        ] {
            if left != right {
                report.push(format!(
                    "{label}: {field} {} -> {}",
                    left.join(","),
                    right.join(",")
                ));
            }
        }
        for transport in TRANSPORTS {
            let changed: Vec<_> = callers
                .iter()
                .filter(|caller| {
                    admits(left, transport, caller) != admits(right, transport, caller)
                })
                .collect();
            if let Some(first) = changed.first() {
                report.push(format!(
                    "{label}: admission on {} changed for {} callers, e.g. {} {}",
                    snake(transport),
                    changed.len(),
                    Display(first),
                    if admits(right, transport, first) {
                        "now admitted"
                    } else {
                        "now refused"
                    },
                ));
            }
        }
    }
    report
}

fn baseline() -> Table {
    let read = |file| {
        fs::read_to_string(Path::new(env!("CARGO_MANIFEST_DIR")).join(file))
            .expect("the permission baseline must be readable")
    };
    let mut table = parse(&read(BASELINE));
    if !cfg!(windows) {
        for (key, row) in parse(&read(NOT_WINDOWS)) {
            assert!(
                table.insert(key, row).is_some(),
                "a platform row replaces a baseline row"
            );
        }
    }
    table
}

#[test]
#[ignore = "explicit generator; the comparison never writes"]
fn export_permission_baseline() {
    assert!(
        cfg!(windows),
        "export the baseline on Windows; edit {NOT_WINDOWS} for the other platforms"
    );
    fs::write(
        Path::new(env!("CARGO_MANIFEST_DIR")).join(BASELINE),
        render(&current()),
    )
    .expect("the permission baseline must be writable");
}

/// The migration steps that keep authorization unchanged must leave this report empty.
#[test]
fn authorization_matches_the_baseline() {
    let report = differences(&baseline(), &current());
    assert!(report.is_empty(), "{}", report.join("\n"));
}

#[test]
fn baseline_covers_every_resource_once() {
    let table = baseline();
    let count = |kind| table.keys().filter(|(other, _)| *other == kind).count();
    assert_eq!(count(Kind::Command), 210);
    assert_eq!(count(Kind::Event), 17);
    assert_eq!(count(Kind::Route) + count(Kind::Stream), 3);
    assert_eq!(table.len(), 230);

    let names = |kind| -> BTreeSet<String> {
        table
            .keys()
            .filter(|(other, _)| *other == kind)
            .map(|(_, name)| name.clone())
            .collect()
    };
    let commands: BTreeSet<_> = RESOURCES
        .iter()
        .filter(|resource| resource.is_command())
        .map(|command| command.name.to_owned())
        .collect();
    assert_eq!(names(Kind::Command), commands);
    let events: BTreeSet<_> = EventName::ALL
        .iter()
        .map(|event| event.as_str().to_owned())
        .collect();
    assert_eq!(names(Kind::Event), events);
}

/// The comparison's admission model is the production one, for every resource, transport and
/// caller, so an empty report means unchanged production admission. Every capability is
/// provided: capabilities depend on the host and are compared as fields.
#[test]
fn comparison_admits_like_the_production_policy() {
    use nyanpasu_rpc_protocol::ShellCapability;

    let provided: Vec<ShellCapability> = RESOURCES
        .iter()
        .flat_map(|resource| resource.capabilities.iter().copied())
        .collect();
    let authority = crate::permission::Authority::new(&provided);
    let table = current();
    let callers = callers();
    for ((_, name), row) in &table {
        let resource = RESOURCES
            .iter()
            .find(|resource| resource.name == name)
            .unwrap();
        for transport in TRANSPORTS {
            for caller in &callers {
                assert_eq!(
                    admits(row, transport, caller),
                    authority
                        .admit(resource, transport, caller.as_ref())
                        .is_ok(),
                    "{name} on {transport:?} for {}",
                    Display(caller)
                );
            }
        }
    }
}

#[test]
fn comparison_reports_a_changed_requirement() {
    let before = current();
    let mut after = before.clone();
    after
        .get_mut(&(Kind::Command, "select_proxy".to_owned()))
        .unwrap()
        .permission = Permission::new(Resource::Settings, Access::Write);
    let report = differences(&before, &after);
    assert!(
        report
            .contains(&"command select_proxy: permission proxy:write -> settings:write".to_owned()),
        "{report:?}"
    );
    assert!(
        report
            .iter()
            .any(|line| line.starts_with("command select_proxy: admission on http changed")),
        "{report:?}"
    );
}

#[test]
fn comparison_reports_a_changed_marking() {
    let before = current();
    let mut after = before.clone();
    after
        .get_mut(&(Kind::Command, "get_proxies".to_owned()))
        .unwrap()
        .sensitive = true;
    assert_eq!(
        differences(&before, &after),
        ["command get_proxies: sensitive false -> true"]
    );
}

#[test]
fn comparison_reports_a_removed_exposure() {
    let before = current();
    let mut after = before.clone();
    let row = after
        .get_mut(&(Kind::Command, "get_proxies".to_owned()))
        .unwrap();
    row.targets.retain(|target| target != "http");
    let report = differences(&before, &after);
    assert!(
        report.contains(
            &"command get_proxies: targets desktop,http,local -> desktop,local".to_owned()
        ),
        "{report:?}"
    );
    // `get_proxies` requires `proxy:read`: 2 of the 3 levels on proxy, times 3^6 for the rest.
    assert!(
        report.iter().any(|line| line
            .starts_with("command get_proxies: admission on http changed for 1458 callers")),
        "{report:?}"
    );
}

#[test]
fn comparison_of_identical_tables_is_empty() {
    let table = current();
    assert!(differences(&table, &table).is_empty());
    assert_eq!(parse(&render(&table)), table);
}
