//! The reviewed authorization baseline of every protected resource, and the comparison that
//! reports how a later resource table differs from it.
//!
//! A resource is a command, an event, an HTTP route or a stream. The baseline is a committed
//! text table; [`differences`] aligns two tables by `(kind, name)`, compares every field, and
//! compares admission on every transport for the unresolved caller and every subset of the
//! scopes. The permission migration requires an empty difference at every step that is not
//! allowed to change authorization.

use std::{
    collections::{BTreeMap, BTreeSet},
    fmt::{self, Debug, Write as _},
    fs,
    path::Path,
};

use nyanpasu_rpc_protocol::{COMMAND_CATALOG, CommandEffect, EventName, RpcTarget, Scope};

const BASELINE: &str = "tests/fixtures/permission-baseline.txt";
/// The baseline is exported on Windows. These rows replace the commands whose declarations differ
/// on every other platform, where the `cfg(not(windows))` variant is compiled.
const NOT_WINDOWS: &str = "tests/fixtures/permission-baseline-not-windows.txt";
const HEADER: &str = "# Generated by export_permission_baseline; do not edit.\n# kind | name | scope | effect | targets | capabilities | optional_capabilities\n";
const TRANSPORTS: [RpcTarget; 3] = [RpcTarget::Desktop, RpcTarget::Http, RpcTarget::Local];
/// The one command any resolved caller may invoke without holding its scope.
const SELF_INSPECTION: &str = "rpc_describe";

#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord)]
enum Kind {
    Command,
    Event,
    Route,
    Stream,
}

/// One protected resource, with every field that takes part in authorization or availability.
#[derive(Debug, Clone, PartialEq, Eq)]
struct Row {
    scope: String,
    /// `query`/`mutation` for commands; events, routes and streams only read.
    effect: String,
    targets: Vec<String>,
    capabilities: Vec<String>,
    optional_capabilities: Vec<String>,
}

type Table = BTreeMap<(Kind, String), Row>;

/// A caller in the comparison: unresolved (no authentication), or resolved with these scopes.
type Caller = Option<BTreeSet<Scope>>;

fn snake(value: impl Debug) -> String {
    let mut name = String::new();
    for (index, character) in format!("{value:?}").chars().enumerate() {
        if character.is_ascii_uppercase() && index > 0 {
            name.push('_');
        }
        name.push(character.to_ascii_lowercase());
    }
    name
}

fn names<T: Debug + Copy>(values: &[T]) -> Vec<String> {
    values.iter().copied().map(snake).collect()
}

/// The routes and streams whose scope is a literal at their admission site
/// (`http/routes.rs`, `local/server.rs`). They become declarations later in the migration.
fn routes() -> [(Kind, &'static str, Scope, &'static [RpcTarget]); 3] {
    [
        (Kind::Route, "icon_fetch", Scope::Read, &[RpcTarget::Http]),
        (
            Kind::Route,
            "logs_archive",
            Scope::SensitiveRead,
            &[RpcTarget::Http],
        ),
        (
            Kind::Stream,
            "connection_details",
            Scope::Read,
            &[RpcTarget::Http, RpcTarget::Local],
        ),
    ]
}

/// The table the current code authorizes against.
fn current() -> Table {
    let mut table = Table::new();
    for command in COMMAND_CATALOG {
        let row = Row {
            scope: command.scope.as_str().to_owned(),
            effect: match command.effect {
                CommandEffect::Query => "query",
                CommandEffect::Mutation => "mutation",
            }
            .to_owned(),
            targets: names(command.targets),
            capabilities: names(command.capabilities),
            optional_capabilities: names(command.optional_capabilities),
        };
        let previous = table.insert((Kind::Command, command.name.to_owned()), row);
        assert!(previous.is_none(), "duplicate command {}", command.name);
    }
    for event in EventName::ALL {
        let row = Row {
            scope: event.scope().as_str().to_owned(),
            effect: "read".to_owned(),
            targets: names(event.targets()),
            capabilities: names(event.capability().as_slice()),
            optional_capabilities: Vec::new(),
        };
        table.insert((Kind::Event, event.as_str().to_owned()), row);
    }
    for (kind, name, scope, targets) in routes() {
        let row = Row {
            scope: scope.as_str().to_owned(),
            effect: "read".to_owned(),
            targets: names(targets),
            capabilities: Vec::new(),
            optional_capabilities: Vec::new(),
        };
        table.insert((kind, name.to_owned()), row);
    }
    table
}

fn render(table: &Table) -> String {
    let mut output = String::from(HEADER);
    for ((kind, name), row) in table {
        let line = format!(
            "{} | {name} | {} | {} | {} | {} | {}",
            snake(kind),
            row.scope,
            row.effect,
            row.targets.join(","),
            row.capabilities.join(","),
            row.optional_capabilities.join(","),
        );
        writeln!(output, "{}", line.trim_end()).unwrap();
    }
    output
}

fn parse(text: &str) -> Table {
    let list = |field: &str| -> Vec<String> {
        field
            .split(',')
            .filter(|value| !value.is_empty())
            .map(str::to_owned)
            .collect()
    };
    let mut table = Table::new();
    for line in text.lines().filter(|line| !line.starts_with('#')) {
        let columns: Vec<_> = line.split('|').map(str::trim).collect();
        assert_eq!(columns.len(), 7, "malformed row: {line}");
        let kind = match columns[0] {
            "command" => Kind::Command,
            "event" => Kind::Event,
            "route" => Kind::Route,
            "stream" => Kind::Stream,
            other => panic!("unknown resource kind {other}"),
        };
        let row = Row {
            scope: columns[2].to_owned(),
            effect: columns[3].to_owned(),
            targets: list(columns[4]),
            capabilities: list(columns[5]),
            optional_capabilities: list(columns[6]),
        };
        let previous = table.insert((kind, columns[1].to_owned()), row);
        assert!(previous.is_none(), "duplicate row: {line}");
    }
    table
}

/// The unresolved caller and every subset of the scopes.
fn callers() -> Vec<Caller> {
    let mut callers = vec![None];
    for mask in 0..1_u32 << Scope::ALL.len() {
        let scopes = Scope::ALL
            .iter()
            .enumerate()
            .filter(|(bit, _)| mask & (1 << bit) != 0)
            .map(|(_, scope)| *scope)
            .collect();
        callers.push(Some(scopes));
    }
    callers
}

/// Whether `caller` is admitted to `row` on `transport`: authentication, exposure, then the
/// scope, with the self-inspection exception. Capabilities depend on the host and are compared
/// as fields instead.
fn admits(kind: Kind, name: &str, row: &Row, transport: RpcTarget, caller: &Caller) -> bool {
    let Some(scopes) = caller else { return false };
    row.targets.contains(&snake(transport))
        && ((kind == Kind::Command && name == SELF_INSPECTION)
            || scopes.iter().any(|scope| scope.as_str() == row.scope))
}

struct Display<'a>(&'a Caller);

impl fmt::Display for Display<'_> {
    fn fmt(&self, f: &mut fmt::Formatter<'_>) -> fmt::Result {
        match self.0 {
            None => f.write_str("unresolved"),
            Some(scopes) => {
                let scopes: Vec<_> = scopes.iter().map(|scope| scope.as_str()).collect();
                write!(f, "{{{}}}", scopes.join(","))
            }
        }
    }
}

/// Every difference between two tables, one line each: added and removed resources, changed
/// fields, and per transport the callers whose admission changed.
fn differences(before: &Table, after: &Table) -> Vec<String> {
    let callers = callers();
    let mut report = Vec::new();
    let keys: BTreeSet<_> = before.keys().chain(after.keys()).collect();
    for key @ (kind, name) in keys {
        let label = format!("{} {name}", snake(kind));
        let (left, right) = match (before.get(key), after.get(key)) {
            (Some(left), Some(right)) => (left, right),
            (Some(_), None) => {
                report.push(format!("{label}: removed"));
                continue;
            }
            (None, Some(_)) => {
                report.push(format!("{label}: added"));
                continue;
            }
            (None, None) => unreachable!(),
        };
        for (field, left, right) in [
            ("scope", vec![left.scope.clone()], vec![right.scope.clone()]),
            (
                "effect",
                vec![left.effect.clone()],
                vec![right.effect.clone()],
            ),
            ("targets", left.targets.clone(), right.targets.clone()),
            (
                "capabilities",
                left.capabilities.clone(),
                right.capabilities.clone(),
            ),
            (
                "optional_capabilities",
                left.optional_capabilities.clone(),
                right.optional_capabilities.clone(),
            ),
        ] {
            if left != right {
                report.push(format!(
                    "{label}: {field} {} -> {}",
                    left.join(","),
                    right.join(",")
                ));
            }
        }
        for transport in TRANSPORTS {
            let changed: Vec<_> = callers
                .iter()
                .filter(|caller| {
                    admits(*kind, name, left, transport, caller)
                        != admits(*kind, name, right, transport, caller)
                })
                .collect();
            if let Some(first) = changed.first() {
                report.push(format!(
                    "{label}: admission on {} changed for {} callers, e.g. {} {}",
                    snake(transport),
                    changed.len(),
                    Display(first),
                    if admits(*kind, name, right, transport, first) {
                        "now admitted"
                    } else {
                        "now refused"
                    },
                ));
            }
        }
    }
    report
}

fn baseline() -> Table {
    let read = |file| {
        fs::read_to_string(Path::new(env!("CARGO_MANIFEST_DIR")).join(file))
            .expect("the permission baseline must be readable")
    };
    let mut table = parse(&read(BASELINE));
    if !cfg!(windows) {
        for (key, row) in parse(&read(NOT_WINDOWS)) {
            assert!(
                table.insert(key, row).is_some(),
                "a platform row replaces a baseline row"
            );
        }
    }
    table
}

#[test]
#[ignore = "explicit generator; the comparison never writes"]
fn export_permission_baseline() {
    assert!(
        cfg!(windows),
        "export the baseline on Windows; edit {NOT_WINDOWS} for the other platforms"
    );
    fs::write(
        Path::new(env!("CARGO_MANIFEST_DIR")).join(BASELINE),
        render(&current()),
    )
    .expect("the permission baseline must be writable");
}

/// The migration steps that keep authorization unchanged must leave this report empty.
#[test]
fn authorization_matches_the_baseline() {
    let report = differences(&baseline(), &current());
    assert!(report.is_empty(), "{}", report.join("\n"));
}

#[test]
fn baseline_covers_every_resource_once() {
    let table = baseline();
    let count = |kind| table.keys().filter(|(other, _)| *other == kind).count();
    assert_eq!(count(Kind::Command), 205);
    assert_eq!(count(Kind::Event), 17);
    assert_eq!(count(Kind::Route) + count(Kind::Stream), 3);
    assert_eq!(table.len(), 225);

    let names = |kind| -> BTreeSet<String> {
        table
            .keys()
            .filter(|(other, _)| *other == kind)
            .map(|(_, name)| name.clone())
            .collect()
    };
    let commands: BTreeSet<_> = COMMAND_CATALOG
        .iter()
        .map(|command| command.name.to_owned())
        .collect();
    assert_eq!(names(Kind::Command), commands);
    let events: BTreeSet<_> = EventName::ALL
        .iter()
        .map(|event| event.as_str().to_owned())
        .collect();
    assert_eq!(names(Kind::Event), events);
}

/// The comparison's admission model is the production one, for every command, transport and
/// caller, so an empty report means unchanged production admission.
#[test]
fn comparison_admits_like_the_production_policy() {
    use nyanpasu_rpc_protocol::{AuthContext, Principal};

    let table = current();
    for command in COMMAND_CATALOG {
        let row = &table[&(Kind::Command, command.name.to_owned())];
        for transport in TRANSPORTS {
            for caller in callers() {
                let expected = caller.as_ref().is_some_and(|scopes| {
                    let auth =
                        AuthContext::new(Principal::Anonymous, scopes.iter().copied().collect());
                    crate::policy::is_command_allowed(command, true, true, true, transport, &auth)
                });
                assert_eq!(
                    admits(Kind::Command, command.name, row, transport, &caller),
                    expected,
                    "{} on {transport:?} for {}",
                    command.name,
                    Display(&caller)
                );
            }
        }
    }
}

#[test]
fn comparison_reports_a_changed_requirement() {
    let before = current();
    let mut after = before.clone();
    after
        .get_mut(&(Kind::Command, "select_proxy".to_owned()))
        .unwrap()
        .scope = "settings".to_owned();
    let report = differences(&before, &after);
    assert!(
        report.contains(&"command select_proxy: scope proxy -> settings".to_owned()),
        "{report:?}"
    );
    assert!(
        report
            .iter()
            .any(|line| line.starts_with("command select_proxy: admission on http changed")),
        "{report:?}"
    );
}

#[test]
fn comparison_reports_a_removed_exposure() {
    let before = current();
    let mut after = before.clone();
    let row = after
        .get_mut(&(Kind::Command, "get_proxies".to_owned()))
        .unwrap();
    row.targets.retain(|target| target != "http");
    let report = differences(&before, &after);
    assert!(
        report.contains(
            &"command get_proxies: targets desktop,http,local -> desktop,local".to_owned()
        ),
        "{report:?}"
    );
    assert!(
        report.iter().any(|line| line
            .starts_with("command get_proxies: admission on http changed for 64 callers")),
        "{report:?}"
    );
}

#[test]
fn comparison_of_identical_tables_is_empty() {
    let table = current();
    assert!(differences(&table, &table).is_empty());
    assert_eq!(parse(&render(&table)), table);
}
